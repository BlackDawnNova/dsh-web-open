// 下载链接拦截:点击下载链接 → 打开自己的目录选择器标签页(下载/下载到默认目录/取消)
// (绕开 Electron will-download 的 item 销毁 bug:在下载开始前由用户确认)
(function () {
  var DL_RE = /\.(zip|rar|7z|tar|gz|exe|msi|apk|dmg|pkg|iso|pdf|docx?|xlsx?|pptx?|mp3|mp4|mov|dll|jar|bin|whl)$/i;
  document.addEventListener('click', function (e) {
    var a = e.target && e.target.closest ? e.target.closest('a[href]') : null;
    if (!a || !a.href) return;
    if (!/^https?:\/\//i.test(a.href)) return;
    var isDl = a.hasAttribute('download') || DL_RE.test(a.href.split('?')[0].split('#')[0]);
    if (!isDl) return;
    e.preventDefault();
    e.stopPropagation();
    var name = a.getAttribute('download') || decodeURIComponent(a.href.split('/').pop().split('?')[0]) || 'file';
    ipcRenderer.invoke('dsh:webbox-downloads', 'open-dl-picker', { url: a.href, name: name }).then(function (choice) {
      if (choice === 'download') window.location.href = a.href; // 确认后放行(will-download 用临时目录)
      // 'cancel' → 已 preventDefault,什么都不做
    });
  }, true);
})();
